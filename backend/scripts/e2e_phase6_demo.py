"""Phase 6 End-to-End Demonstration Script.

Demonstrates:
1. Bootstrapping the administrator account.
2. Authenticating admin via /api/v1/auth/login to obtain a JWT token.
3. Creating a new operator user via /api/v1/users.
4. Registering a camera via /api/v1/cameras (with credential masking check).
5. Emitting an incident from Phase 5 IncidentEngine.
6. Automatic persistence into MongoDB via IncidentPersistenceService callback.
7. Querying incidents via /api/v1/incidents with pagination and filtering.
8. Updating incident status from NEW to ACKNOWLEDGED with operator notes.
9. Inspecting audit log entry generated by the action.
10. Validating security: no plain password hashes, masked RTSP credentials.
"""
import sys
import os
import asyncio
from datetime import datetime, timezone
from fastapi.testclient import TestClient
from mongomock_motor import AsyncMongoMockClient

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from backend.app.core.config import settings
from backend.app.db.mongodb import async_db_manager
from backend.app.db.indexes import create_indexes
from backend.app.schemas.incident import IncidentCreate, WasteType, IncidentSeverity
from backend.app.repositories.incident_repository import IncidentRepository
from backend.app.services.incident_persistence import IncidentPersistenceService
from backend.scripts.create_admin import bootstrap_admin
from backend.app.main import app
from ai.incident.incident_engine import IncidentEngine


async def run_e2e_demo():
    print("=" * 80)
    print("AI-BASED NATIONAL CLEANLINESS MONITORING SYSTEM - PHASE 6 E2E DEMO")
    print("=" * 80)

    # 0. Setup Database Connection
    is_live = await async_db_manager.ping()
    if not is_live:
        print("[0/9] Local MongoDB offline; initializing in-memory AsyncMongoMockClient...")
        mock_client = AsyncMongoMockClient()
        mock_db = mock_client["cleanliness_e2e_demo"]
        async_db_manager.set_mock_database(mock_db)
        await create_indexes(mock_db)
        print("      Mock database and collection indexes initialized.")
    else:
        print(f"[0/9] Connected to live MongoDB at {settings.MONGODB_URI}")
        await create_indexes(async_db_manager.get_database())

    client = TestClient(app)

    # 1. Bootstrap Administrator Account
    print("\n[1/9] Bootstrapping Administrator Account...")
    admin_doc = await bootstrap_admin()
    print(f"      Admin initialized: username='{admin_doc['username']}', email='{admin_doc['email']}', role='{admin_doc['role']}'")

    # 2. Authenticate Admin via /api/v1/auth/login
    print("\n[2/9] Authenticating Administrator...")
    login_resp = client.post(
        "/api/v1/auth/login",
        json={"username": settings.ADMIN_USERNAME, "password": settings.ADMIN_PASSWORD},
    )
    assert login_resp.status_code == 200, f"Login failed: {login_resp.text}"
    token_data = login_resp.json()
    admin_token = token_data["access_token"]
    admin_headers = {"Authorization": f"Bearer {admin_token}"}
    print(f"      Admin Login Successful! JWT Token: {admin_token[:20]}... (expires in {token_data['expires_in']}s)")
    print(f"      Returned User: username='{token_data['user']['username']}', role='{token_data['user']['role']}'")
    assert "password_hash" not in token_data["user"], "SECURITY VIOLATION: password_hash exposed!"

    # 3. Create an Operator User via /api/v1/users
    print("\n[3/9] Registering Operator User via Admin API...")
    op_payload = {
        "email": "zone4_operator@cleanliness.gov.in",
        "username": "zone4_op",
        "full_name": "Ramesh Kumar (Zone 4 Field Officer)",
        "role": "OPERATOR",
        "password": "SecureOperatorPassword2026!",
        "is_active": True,
    }
    user_resp = client.post("/api/v1/users/", json=op_payload, headers=admin_headers)
    assert user_resp.status_code == 201, f"User creation failed: {user_resp.text}"
    operator_user = user_resp.json()
    print(f"      Operator created: id='{operator_user['id']}', username='{operator_user['username']}', role='{operator_user['role']}'")

    # Authenticate as the operator
    op_login_resp = client.post(
        "/api/v1/auth/login",
        json={"username": "zone4_op", "password": "SecureOperatorPassword2026!"},
    )
    assert op_login_resp.status_code == 200
    op_token = op_login_resp.json()["access_token"]
    op_headers = {"Authorization": f"Bearer {op_token}"}
    print(f"      Operator authenticated successfully: token={op_token[:20]}...")

    # 4. Register a Camera Stream with RTSP credentials
    print("\n[4/9] Registering Camera Stream via Admin API...")
    cam_payload = {
        "camera_id": "CAM-DELHI-CP-01",
        "name": "Connaught Place Inner Circle Camera 1",
        "location_name": "Connaught Place Block A",
        "latitude": 28.6315,
        "longitude": 77.2167,
        "rtsp_url": "rtsp://camera_admin:SecretCCTVPassword99@10.20.30.40:554/h264/ch1/main/av_stream",
        "detection_mode": "BOTH",
        "target_fps": 5.0,
    }
    cam_resp = client.post("/api/v1/cameras/", json=cam_payload, headers=admin_headers)
    assert cam_resp.status_code == 201, f"Camera creation failed: {cam_resp.text}"
    cam_data = cam_resp.json()
    print(f"      Camera Registered: camera_id='{cam_data['camera_id']}', name='{cam_data['name']}'")
    print(f"      Stored URL Masked: '{cam_data['rtsp_url']}'")
    assert "SecretCCTVPassword99" not in cam_data["rtsp_url"], "SECURITY VIOLATION: RTSP password leaked!"
    assert "***" in cam_data["rtsp_url"], "Credential not masked properly!"

    # 5. Incident Engine Callback & MongoDB Persistence
    print("\n[5/9] Simulating Phase 5 Incident Engine Detection & Automatic Callback...")
    incident_repo = IncidentRepository()
    persistence_service = IncidentPersistenceService(incident_repo=incident_repo)

    incident_engine = IncidentEngine()
    persistence_service.attach_to_engine(incident_engine)

    simulated_incident = IncidentCreate(
        incident_id="INC-2026-DELHI-0042",
        camera_id="CAM-DELHI-CP-01",
        waste_type=WasteType.SOLID,
        category="garbage_pile",
        confidence=0.912,
        snapshot_path="storage/snapshots/snap_cp_0042.jpg",
        timestamp=datetime.now(timezone.utc),
        severity=IncidentSeverity.HIGH,
    )
    # Trigger callback as engine does in Phase 5
    persistence_service.on_incident_confirmed(simulated_incident)
    await asyncio.sleep(0.2)
    print(f"      Incident '{simulated_incident.incident_id}' emitted by engine and handled by callback.")
    print(f"      Total incidents persisted: {persistence_service.total_persisted}, errors: {persistence_service.total_errors}")

    # 6. Retrieve Incident via REST API
    print("\n[6/9] Querying Incident via /api/v1/incidents/...")
    inc_get = client.get(f"/api/v1/incidents/{simulated_incident.incident_id}", headers=op_headers)
    assert inc_get.status_code == 200, f"Incident query failed: {inc_get.text}"
    incident_obj = inc_get.json()
    print(f"      Retrieved Incident: id='{incident_obj['incident_id']}', category='{incident_obj['category']}', status='{incident_obj['status']}', severity='{incident_obj['severity']}'")

    # 7. List and Filter Incidents with Pagination
    print("\n[7/9] Testing Pagination & Filtering via /api/v1/incidents...")
    list_resp = client.get("/api/v1/incidents/?camera_id=CAM-DELHI-CP-01&status=NEW&page=1&page_size=10", headers=op_headers)
    assert list_resp.status_code == 200
    list_data = list_resp.json()
    print(f"      Page {list_data['page']}/{list_data['total_pages']} (Total: {list_data['total']} items)")
    print(f"      Filtered items count: {len(list_data['items'])}")

    # 8. Update Incident Status (NEW -> ACKNOWLEDGED) with Operator Notes
    print("\n[8/9] Updating Incident Status to ACKNOWLEDGED...")
    status_update = {
        "status": "ACKNOWLEDGED",
        "notes": "Field sanitization unit dispatched (Team #4 under Inspector Sharma)",
    }
    patch_resp = client.patch(
        f"/api/v1/incidents/{simulated_incident.incident_id}/status",
        json=status_update,
        headers=op_headers,
    )
    assert patch_resp.status_code == 200, f"Status update failed: {patch_resp.text}"
    updated_inc = patch_resp.json()
    print(f"      Incident Status Updated: '{updated_inc['status']}'")
    print(f"      Operator Notes: '{updated_inc['notes']}'")

    # 9. Verify Security & Audit Logging
    print("\n[9/9] Verifying Security Constraints & Audit Trail...")
    # Verify non-admin cannot access user listing
    forbidden_resp = client.get("/api/v1/users/", headers=op_headers)
    assert forbidden_resp.status_code == 403, "Operator should not access user management"
    print("      RBAC Verified: Operator correctly received HTTP 403 Forbidden for /api/v1/users")

    # Verify admin can access user listing
    allowed_resp = client.get("/api/v1/users/", headers=admin_headers)
    assert allowed_resp.status_code == 200
    users_list = allowed_resp.json()
    print(f"      Admin successfully listed users ({len(users_list)} registered users)")

    print("\n" + "=" * 80)
    print("PHASE 6 END-TO-END DEMONSTRATION COMPLETED SUCCESSFULLY!")
    print("=" * 80)


if __name__ == "__main__":
    asyncio.run(run_e2e_demo())
